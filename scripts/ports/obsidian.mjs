export const themeCss = (night, paper) => `/* Living Code for Obsidian. Dark mode is Night, light mode is Paper.
   Generated by scripts/build.mjs from ${REPO}. Frost and Signal are dark flavors:
   copy a file from snippets/ into <vault>/.obsidian/snippets/ and enable it under Appearance > CSS snippets. */

.theme-dark {
${decl(obsidianVariables(night))}
}

.theme-light {
${decl(obsidianVariables(paper))}
}

body {
  --bold-color: var(--text-normal);
  --italic-color: var(--text-normal);
}

.markdown-rendered strong, .cm-strong { color: var(--bold-color); }
.markdown-rendered em, .cm-em { color: var(--italic-color); }
.markdown-rendered code, .cm-inline-code { color: var(--code-normal); }
.markdown-rendered mark, .cm-highlight { color: var(--text-normal); }
.cm-s-obsidian .cm-formatting-header, .cm-s-obsidian .cm-header { color: var(--h1-color); }
`;

export const snippetCss = (f) => `/* Living Code ${f.name.replace("Living Code ", "")} for Obsidian. A dark flavor, so it replaces the dark mode colors of the Living Code theme.
   Enable the "Living Code" theme first, then turn this snippet on under Appearance > CSS snippets. */

.theme-dark {
${decl(obsidianVariables(f))}
}
`;

const manifest = () => JSON.stringify({
  name: "Living Code",
  version: OBSIDIAN_VERSION,
  minAppVersion: MIN_APP_VERSION,
  author: "Elliot Luque",
  authorUrl: "https://github.com/ElliotLuque",
}, null, 2) + "\n";

const themeReadme = () => `# Living Code for Obsidian

An Obsidian theme from [Living Code](${REPO}). Dark mode is **Night** and light mode is **Paper**, so the theme follows Obsidian's *Appearance → Base color scheme*.

![Living Code Night and Paper](screenshot.png)

## Install

*Settings → Appearance → Themes → Manage*, search for **Living Code** and click **Install and use**.

## Frost and Signal

Frost and Signal are dark flavors, so they ship as CSS snippets. Copy \`snippets/living-code-frost.css\` or \`snippets/living-code-signal.css\` into \`<vault>/.obsidian/snippets/\` and enable it under *Appearance → CSS snippets*. A snippet replaces the dark mode colors of the theme.

## License

MIT
`;

export const obsidian = {
  id: "obsidian",
  name: "Obsidian",
  homepage: "https://obsidian.md",
  files: () => [],
  all: (fs) => {
    const night = fs.find((f) => f.id === "night");
    const paper = fs.find((f) => f.id === "paper");
    return [
      { path: `${DIR}/manifest.json`, content: manifest() },
      { path: `${DIR}/theme.css`, content: themeCss(night, paper) },
      { path: `${DIR}/README.md`, content: themeReadme() },
      { path: `${DIR}/LICENSE`, content: license },
      ...fs.filter((f) => SNIPPET_FLAVORS.includes(f.id)).map((f) => ({ path: `${DIR}/snippets/${f.slug}.css`, content: snippetCss(f) })),
    ];
  },
  install: `Obsidian's dark mode is **Night** and its light mode is **Paper**; the theme follows *Appearance → Base color scheme*.

1. Open *Settings → Appearance → Themes → Manage*, search for **Living Code** and click **Install and use**. This README assumes the theme is listed in Obsidian's community themes.
2. **Without the directory:** copy \`manifest.json\` and \`theme.css\` from [\`extras/obsidian/\`](extras/obsidian) into \`<vault>/.obsidian/themes/Living Code/\`, then pick **Living Code** under *Appearance → Themes*.

**Frost and Signal** are dark flavors, so they ship as CSS snippets rather than as a Style Settings option, which would need a second plugin: copy \`snippets/living-code-frost.css\` or \`snippets/living-code-signal.css\` into \`<vault>/.obsidian/snippets/\` and enable it under *Appearance → CSS snippets*.`,
};
