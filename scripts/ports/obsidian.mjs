// Obsidian community theme. extras/obsidian/ is laid out as the root of the theme's own repository
// (manifest.json, theme.css, README.md, LICENSE, screenshot.png), so publishing is a straight copy.
// Dark mode is Night and light mode is Paper. Frost and Signal are dark flavors, so they ship as CSS snippets.
import { readFileSync } from "node:fs";

export const OBSIDIAN_VERSION = "1.0.0";
export const MIN_APP_VERSION = "1.0.0";
export const SNIPPET_FLAVORS = ["frost", "signal"];
const REPO = "https://github.com/ElliotLuque/living-code";
const DIR = "extras/obsidian";
const license = readFileSync(new URL("../../LICENSE", import.meta.url), "utf8");

const decl = (pairs) => pairs.map(([k, v]) => `  ${k}: ${v};`).join("\n");

